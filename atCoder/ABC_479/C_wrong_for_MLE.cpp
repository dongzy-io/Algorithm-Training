#include<bits/stdc++.h>
using namespace std;

typedef long long ll;

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    int n,w;
    cin>>n>>w;
    vector<ll> dp(w+1,0);
    for(int i=0;i<n;i++){
        ll d;
        int m;
        cin>>d>>m;
        for(int j=w;j>=m;j--){
            dp[j]=max(dp[j],dp[j-m]+d);
        }
    }
    cout<<dp[w];
    return 0;
}
